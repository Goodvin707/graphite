export function createSampleVault(): Vault {
  const now = Date.now()
  return {
    version: 1,
    name: "Мастерская",
    origin: "sample",
    notes: SPECS.map((spec, index) => ({
      id: `sample-${spec.id}`,
      title: spec.title,
      folder: spec.folder,
      content: spec.content.trim(),
      createdAt: now - (SPECS.length - index) * 3_600_000,
      updatedAt: now - (SPECS.length - index) * 1_200_000,
    })),
  }
}

export function createEmptyVault(): Vault {
  return {
    version: 1,
    name: "Мои заметки",
    origin: "empty",
    notes: [],
  }
}
